-- Configuracion inicial de Snowflake para el PSet 2 (ejecutar una vez con ACCOUNTADMIN o SYSADMIN+SECURITYADMIN).
--
-- Antes, genera el par de llaves (ver README, paso 1) y pega el contenido de secrets/rsa_key.pub
-- (sin las lineas BEGIN/END) en RSA_PUBLIC_KEY. Reemplaza tambien <TU_USUARIO> al final.

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS PSET2_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS PSET2_ROSSMANN;
CREATE SCHEMA IF NOT EXISTS PSET2_ROSSMANN.RAW;     -- datos originales cargados por Kestra
CREATE SCHEMA IF NOT EXISTS PSET2_ROSSMANN.BRONZE;  -- dbt: tipado 1:1 con Raw
CREATE SCHEMA IF NOT EXISTS PSET2_ROSSMANN.SILVER;  -- dbt: staging limpio
CREATE SCHEMA IF NOT EXISTS PSET2_ROSSMANN.GOLD;    -- dbt: star schema
CREATE SCHEMA IF NOT EXISTS PSET2_ROSSMANN.OBT;     -- Spark: One Big Table

CREATE ROLE IF NOT EXISTS PSET2_ROLE;
GRANT USAGE, OPERATE ON WAREHOUSE PSET2_WH TO ROLE PSET2_ROLE;
GRANT OWNERSHIP ON DATABASE PSET2_ROSSMANN TO ROLE PSET2_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE PSET2_ROSSMANN TO ROLE PSET2_ROLE COPY CURRENT GRANTS;

-- Usuario de servicio (sin contrasena: Snowflake bloquea el inicio de sesion solo con contrasena)
CREATE USER IF NOT EXISTS PSET2_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = PSET2_ROLE
  DEFAULT_WAREHOUSE = PSET2_WH
  DEFAULT_NAMESPACE = PSET2_ROSSMANN.RAW
  RSA_PUBLIC_KEY = '<PEGA_AQUI_LA_LLAVE_PUBLICA>';
GRANT ROLE PSET2_ROLE TO USER PSET2_SVC;
-- Permite ver las tablas del proyecto desde Snowsight con tu usuario personal
GRANT ROLE PSET2_ROLE TO USER <TU_USUARIO>;
